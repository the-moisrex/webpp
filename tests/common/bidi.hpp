    /// this implementation is correct, but it's using binary search, that's why we implemented it
    /// differently, but we're keeping this implementation for testing and benchmarking purposes.
    template <UTF32 CPType>
    [[nodiscard]] static constexpr direction find_direction(CPType const code_point) noexcept {
        using enum direction;
        auto const pos =
          stl::lower_bound(dirs.begin(), dirs.end(), code_point, [](directions const& dir, auto const cur) {
              return dir.ending < cur;
          });

        if (pos == dirs.end()) [[unlikely]] {
            return NONE;
        }
        if (code_point >= pos->starting) [[likely]] {
            return pos->dir;
        }
        return NONE;
    }

