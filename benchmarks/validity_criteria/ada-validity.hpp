    static inline direction find_direction(uint32_t code_point) noexcept {
        auto it =
          std::lower_bound(std::begin(dir_table), std::end(dir_table), code_point, [](directions const& d, uint32_t c) {
              return d.final_code < c;
          });

        // next check is almost surely in vain, but we use it for safety.
        if (it == std::end(dir_table)) {
            return direction::NONE;
        }
        // We have that d.final_code >= c.
        if (code_point >= it->start_code) {
            return it->direct;
        }
        return direction::NONE;
    }

    static inline size_t find_last_not_of_nsm(std::u32string_view const label) noexcept {
        for (int i = static_cast<int>(label.size() - 1); i >= 0; i--) {
            if (find_direction(label[i]) != direction::NSM) {
                return i;
            }
        }

        return std::u32string_view::npos;
    }

    // An RTL label is a label that contains at least one character of type R, AL,
    // or AN. https://www.rfc-editor.org/rfc/rfc5893#section-2
    static inline bool is_rtl_label(std::u32string_view const label) noexcept {
        size_t const mask = (1u << direction::R) | (1u << direction::AL) | (1u << direction::AN);

        size_t directions = 0;
        for (size_t i = 0; i < label.size(); i++) {
            directions |= 1u << find_direction(label[i]);
        }
        return (directions & mask) != 0;
    }

